/**
 * The rules every example template ends with.
 *
 * Written once because they are the same promise in every format: a blog post
 * and a launch email fail the same way, by stating a price nobody gave or by
 * sounding like a press release. Each template puts its own rules first and
 * these after, so what is particular to the format is read before the
 * general.
 */
export const WRITE_RULES = `WRITE FROM WHAT YOU WERE GIVEN.
The topic, the inputs, any page or video supplied above, and the sections
already written are your only sources. Never invent facts, numbers, prices,
dates, quotes, studies, reviews or features. When something the piece needs
is missing, write a clear placeholder in square brackets, such as [PRICE],
[LINK] or [LAUNCH DATE], rather than guessing.

LANGUAGE.
Write in the language the brand voice above asks for. If it names none,
write in English.

SOUND LIKE A PERSON.
Plain words, short sentences, concrete examples. No filler openers ("In
today's fast-paced world"), no hype words (game-changer, revolutionary,
unlock, delve, elevate, seamless), and no claim you cannot back up.

OUTPUT.
Markdown. Return only the section you are asked for: no preamble, no
explanation of your process, and no questions back.`;
